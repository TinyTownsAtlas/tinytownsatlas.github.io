// Copies assistant/ASSISTANT_CONTEXT.md into src/context.generated.ts so the Worker bundle (and
// tests) need no special bundler rules. Run `npm run embed` after editing the markdown.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "assistant", "ASSISTANT_CONTEXT.md");
const target = join(here, "..", "src", "context.generated.ts");

const text = readFileSync(source, "utf8").replace(/\r\n/g, "\n");
const out =
  "// GENERATED by scripts/embed-context.mjs from assistant/ASSISTANT_CONTEXT.md. Do not edit.\n" +
  `export const ASSISTANT_CONTEXT = ${JSON.stringify(text)};\n`;
writeFileSync(target, out, "utf8");
console.log(`Embedded ${text.length} characters from assistant/ASSISTANT_CONTEXT.md`);
